public class Main{
    static void main(String[] args) {
        int i = 1; //initialization
        while(i <= 10){ // condition
            System.out.println(i); // actual work
            i = i + 1; // updating the condition
        }
        int num = 100;
        while(num > 0){
            System.out.println(num);
            num -= 1;
        }
    }
}
