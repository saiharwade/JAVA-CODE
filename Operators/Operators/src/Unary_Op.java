public class Unary_Op {
    static void main() {
        // - + ++ --

        int  p = 5;
        System.out.println(p++); // here we are first printing the p so it will print p and then increment the p.
        System.out.println(p);
        System.out.println(++p); // here we are first incrementing then we are printing.
        System.out.println(p);
    }
}
